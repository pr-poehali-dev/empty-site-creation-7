"""Рабочие дни по производственному календарю РФ — пятидневка (5/2).

Каждый год — свой список: будни, которые не работаем (праздники и переносы),
и субботы/воскресенья, которые работаем (перенесённые). Новый год добавлять сюда,
когда правительство утвердит переносы (обычно в сентябре).
"""
from datetime import date, timedelta

# 2026 — ПП РФ от 24.09.2025 № 1466
# 2027 — ПП РФ от 17.09.2026 № 1187
CALENDAR = {
    2026: {
        'off': ['01-01', '01-02', '01-05', '01-06', '01-07', '01-08', '01-09',
                '02-23', '03-09', '05-01', '05-11', '06-12', '11-04', '12-31'],
        'work': [],
    },
    2027: {
        'off': ['01-01', '01-04', '01-05', '01-06', '01-07', '01-08',
                '02-22', '02-23', '03-08', '05-03', '05-10', '06-14',
                '11-04', '11-05', '12-31'],
        'work': ['02-20'],
    },
}

# Года без утверждённого календаря: праздники по ст. 112 ТК РФ, без переносов.
FIXED = ['01-01', '01-02', '01-03', '01-04', '01-05', '01-06', '01-07', '01-08',
         '02-23', '03-08', '05-01', '05-09', '06-12', '11-04']


def _is_workday(d: date) -> bool:
    md = d.strftime('%m-%d')
    cal = CALENDAR.get(d.year)
    if cal:
        if md in cal['work']:
            return True
        if md in cal['off']:
            return False
        return d.weekday() < 5
    return d.weekday() < 5 and md not in FIXED


def count_workdays(start: date, end: date) -> int:
    if not start or not end or end < start:
        return 0
    n, d = 0, start
    while d <= end:
        if _is_workday(d):
            n += 1
        d += timedelta(days=1)
    return n


def known_year(y: int) -> bool:
    return y in CALENDAR


def plural_days(n: int) -> str:
    """«раб. день / дня / дней» — по правилам русского языка."""
    if n % 10 == 1 and n % 100 != 11:
        w = 'день'
    elif 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        w = 'дня'
    else:
        w = 'дней'
    return f'{n} раб. {w}'
